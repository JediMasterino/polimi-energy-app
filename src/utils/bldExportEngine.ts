/**
 * Generate CSV simulation export
 */
export function generateSimulationCsv(data: ExportProjectPayload): string {
  const { projectName, climate, sim } = data;
  const rows: string[] = [];

  rows.push(`Project,${projectName}`);
  rows.push(`Climate,${climate.name}`);
  rows.push(`Gross Floor Area (m2),${sim.gfa}`);
  rows.push(`Compactness S/V (m-1),${sim.svRatio.toFixed(3)}`);
  rows.push(`Net Site EUI (kWh/m2yr),${sim.netSiteEui.toFixed(1)}`);
  rows.push(`Whole-Life Carbon (kgCO2e/m2),${sim.lca.wholeLifeCarbonNet}`);
  rows.push('');
  rows.push('Zone,Floor Area (m2),Facade Area (m2),WWR (%),Urban Shading Factor,Daylight Factor (%),Annual Solar Gain (kWh/m2)');

  for (const z of Object.values(sim.zones)) {
    rows.push(`${z.name},${z.floorAreaM2.toFixed(1)},${z.facadeAreaM2.toFixed(1)},${z.wwrPct.toFixed(0)},${z.urbanShadingFactor.toFixed(2)},${z.daylightFactorPct.toFixed(1)},${z.annualSolarGainKwhM2.toFixed(1)}`);
  }

  return rows.join('\n');
}
